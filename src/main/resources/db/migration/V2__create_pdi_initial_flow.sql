-- TalentSynk: initial PDI flow. No seeds or changes to CORE V1.
-- Configure Flyway to use schema public. CORE user IDs remain application UUIDs.
-- Content validation at submission/approval, authority, immutable submitted content,
-- append-only events and aggregate transitions are enforced by transactional services.

CREATE TABLE pdi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id UUID NOT NULL REFERENCES usuario(id) ON DELETE NO ACTION,
    versao_vigente_id BIGINT,
    status_execucao VARCHAR(32) NOT NULL DEFAULT 'NAO_INICIADO',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    iniciado_em TIMESTAMPTZ,
    concluido_em TIMESTAMPTZ,
    concluido_por_id UUID REFERENCES usuario(id) ON DELETE NO ACTION,
    lock_version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_pdi_execucao CHECK (status_execucao IN ('NAO_INICIADO', 'EM_EXECUCAO', 'CONCLUIDO')),
    CONSTRAINT ck_pdi_lock_version CHECK (lock_version >= 0),
    CONSTRAINT ck_pdi_execucao_datas CHECK (
        (status_execucao = 'NAO_INICIADO' AND iniciado_em IS NULL AND concluido_em IS NULL AND concluido_por_id IS NULL)
        OR (status_execucao = 'EM_EXECUCAO' AND iniciado_em IS NOT NULL AND concluido_em IS NULL AND concluido_por_id IS NULL)
        OR (status_execucao = 'CONCLUIDO' AND iniciado_em IS NOT NULL AND concluido_em >= iniciado_em AND concluido_por_id IS NOT NULL)
    ),
    CONSTRAINT ck_pdi_conclusao_data CHECK (status_execucao <> 'CONCLUIDO' OR concluido_em IS NOT NULL),
    CONSTRAINT ck_pdi_execucao_versao CHECK (status_execucao = 'NAO_INICIADO' OR versao_vigente_id IS NOT NULL)
);

CREATE TABLE pdi_versao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pdi_id BIGINT NOT NULL REFERENCES pdi(id) ON DELETE NO ACTION,
    numero INTEGER NOT NULL CHECK (numero > 0),
    titulo TEXT,
    objetivo TEXT,
    inicio_planejado DATE,
    fim_planejado DATE,
    status_aprovacao VARCHAR(32) NOT NULL DEFAULT 'RASCUNHO',
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submetida_em TIMESTAMPTZ,
    gestor_na_submissao_id UUID REFERENCES usuario(id) ON DELETE NO ACTION,
    decidida_em TIMESTAMPTZ,
    decidido_por_id UUID REFERENCES usuario(id) ON DELETE NO ACTION,
    justificativa_decisao TEXT,
    retirada_em TIMESTAMPTZ,
    CONSTRAINT uq_pdi_versao_numero UNIQUE (pdi_id, numero),
    CONSTRAINT uq_pdi_versao_pertencimento UNIQUE (pdi_id, id),
    CONSTRAINT ck_pdi_versao_datas CHECK (inicio_planejado IS NULL OR fim_planejado IS NULL OR inicio_planejado <= fim_planejado),
    CONSTRAINT ck_pdi_versao_status CHECK (status_aprovacao IN ('RASCUNHO', 'AGUARDANDO_APROVACAO', 'APROVADO', 'REPROVADO', 'RETIRADA')),
    CONSTRAINT ck_pdi_versao_fluxo CHECK (
        (status_aprovacao = 'RASCUNHO' AND submetida_em IS NULL AND decidida_em IS NULL AND decidido_por_id IS NULL AND retirada_em IS NULL)
        OR (status_aprovacao = 'AGUARDANDO_APROVACAO' AND submetida_em IS NOT NULL AND decidida_em IS NULL AND decidido_por_id IS NULL AND retirada_em IS NULL)
        OR (status_aprovacao IN ('APROVADO', 'REPROVADO') AND submetida_em IS NOT NULL AND decidida_em IS NOT NULL AND decidido_por_id IS NOT NULL AND retirada_em IS NULL)
        OR (status_aprovacao = 'RETIRADA' AND submetida_em IS NOT NULL AND retirada_em IS NOT NULL AND decidida_em IS NULL AND decidido_por_id IS NULL)
    ),
    CONSTRAINT ck_pdi_versao_reprovacao CHECK (status_aprovacao <> 'REPROVADO' OR NULLIF(BTRIM(justificativa_decisao), '') IS NOT NULL),
    CONSTRAINT ck_pdi_versao_submissao_data CHECK (submetida_em IS NULL OR submetida_em >= criada_em),
    CONSTRAINT ck_pdi_versao_decisao_data CHECK (decidida_em IS NULL OR decidida_em >= submetida_em),
    CONSTRAINT ck_pdi_versao_retirada_data CHECK (retirada_em IS NULL OR retirada_em >= submetida_em)
);

ALTER TABLE pdi ADD CONSTRAINT fk_pdi_versao_vigente
    FOREIGN KEY (id, versao_vigente_id) REFERENCES pdi_versao(pdi_id, id) ON DELETE NO ACTION;

CREATE TABLE acao_pdi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pdi_id BIGINT NOT NULL REFERENCES pdi(id) ON DELETE NO ACTION,
    status_execucao VARCHAR(32) NOT NULL DEFAULT 'NAO_INICIADA',
    iniciada_em TIMESTAMPTZ,
    concluida_em TIMESTAMPTZ,
    concluida_por_id UUID REFERENCES usuario(id) ON DELETE NO ACTION,
    CONSTRAINT uq_acao_pdi_pertencimento UNIQUE (pdi_id, id),
    CONSTRAINT ck_acao_pdi_execucao CHECK (status_execucao IN ('NAO_INICIADA', 'EM_EXECUCAO', 'CONCLUIDA')),
    CONSTRAINT ck_acao_pdi_execucao_datas CHECK (
        (status_execucao = 'NAO_INICIADA' AND iniciada_em IS NULL AND concluida_em IS NULL AND concluida_por_id IS NULL)
        OR (status_execucao = 'EM_EXECUCAO' AND iniciada_em IS NOT NULL AND concluida_em IS NULL AND concluida_por_id IS NULL)
        OR (status_execucao = 'CONCLUIDA' AND iniciada_em IS NOT NULL AND concluida_em >= iniciada_em AND concluida_por_id IS NOT NULL)
    ),
    CONSTRAINT ck_acao_pdi_conclusao_data CHECK (status_execucao <> 'CONCLUIDA' OR concluida_em IS NOT NULL)
);

CREATE TABLE acao_pdi_versao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pdi_id BIGINT NOT NULL,
    pdi_versao_id BIGINT NOT NULL,
    acao_pdi_id BIGINT NOT NULL,
    titulo TEXT,
    objetivo TEXT,
    resultado_esperado TEXT,
    inicio_planejado DATE,
    fim_planejado DATE,
    ordem INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_acao_versao_plano FOREIGN KEY (pdi_id, pdi_versao_id) REFERENCES pdi_versao(pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT fk_acao_versao_identidade FOREIGN KEY (pdi_id, acao_pdi_id) REFERENCES acao_pdi(pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT uq_acao_versao UNIQUE (pdi_versao_id, acao_pdi_id),
    CONSTRAINT uq_acao_versao_pertencimento UNIQUE (acao_pdi_id, id),
    CONSTRAINT ck_acao_versao_datas CHECK (inicio_planejado IS NULL OR fim_planejado IS NULL OR inicio_planejado <= fim_planejado)
);

CREATE TABLE pdi_componente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao_pdi_id BIGINT NOT NULL REFERENCES acao_pdi(id) ON DELETE NO ACTION,
    tipo VARCHAR(32) NOT NULL DEFAULT 'ENTREGA_VERIFICAVEL',
    status_validacao VARCHAR(32) NOT NULL DEFAULT 'PENDENTE',
    CONSTRAINT uq_componente_pertencimento UNIQUE (acao_pdi_id, id),
    CONSTRAINT ck_componente_tipo CHECK (tipo = 'ENTREGA_VERIFICAVEL'),
    CONSTRAINT ck_componente_validacao CHECK (status_validacao IN ('PENDENTE', 'AGUARDANDO_VALIDACAO', 'RECUSADA', 'VALIDADA'))
);

CREATE TABLE pdi_componente_versao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao_pdi_id BIGINT NOT NULL,
    acao_pdi_versao_id BIGINT NOT NULL,
    componente_id BIGINT NOT NULL,
    peso NUMERIC(5,2),
    descricao TEXT,
    criterio_aceite TEXT,
    forma_comprovacao TEXT,
    CONSTRAINT fk_componente_versao_acao FOREIGN KEY (acao_pdi_id, acao_pdi_versao_id) REFERENCES acao_pdi_versao(acao_pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT fk_componente_versao_identidade FOREIGN KEY (acao_pdi_id, componente_id) REFERENCES pdi_componente(acao_pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT uq_componente_versao UNIQUE (acao_pdi_versao_id, componente_id),
    CONSTRAINT ck_componente_peso CHECK (peso IS NULL OR (peso > 0 AND peso <= 100))
);

CREATE TABLE entrega_submissao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    componente_versao_id BIGINT NOT NULL REFERENCES pdi_componente_versao(id) ON DELETE NO ACTION,
    submetida_por_id UUID NOT NULL REFERENCES usuario(id) ON DELETE NO ACTION,
    submetida_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comprovacao_texto TEXT,
    comprovacao_url TEXT,
    resultado VARCHAR(32) NOT NULL DEFAULT 'PENDENTE',
    encerrada_em TIMESTAMPTZ,
    decidida_por_id UUID REFERENCES usuario(id) ON DELETE NO ACTION,
    justificativa TEXT,
    CONSTRAINT ck_entrega_comprovacao CHECK (NULLIF(BTRIM(comprovacao_texto), '') IS NOT NULL OR NULLIF(BTRIM(comprovacao_url), '') IS NOT NULL),
    CONSTRAINT ck_entrega_resultado CHECK (resultado IN ('PENDENTE', 'VALIDADA', 'RECUSADA', 'RETIRADA')),
    CONSTRAINT ck_entrega_fluxo CHECK (
        (resultado = 'PENDENTE' AND encerrada_em IS NULL AND decidida_por_id IS NULL)
        OR (resultado IN ('VALIDADA', 'RECUSADA') AND encerrada_em IS NOT NULL AND decidida_por_id IS NOT NULL)
        OR (resultado = 'RETIRADA' AND encerrada_em IS NOT NULL AND decidida_por_id IS NULL)
    ),
    CONSTRAINT ck_entrega_recusa CHECK (resultado <> 'RECUSADA' OR NULLIF(BTRIM(justificativa), '') IS NOT NULL),
    CONSTRAINT ck_entrega_encerramento_data CHECK (encerrada_em IS NULL OR encerrada_em >= submetida_em)
);

CREATE TABLE pdi_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pdi_id BIGINT NOT NULL,
    pdi_versao_id BIGINT NOT NULL,
    acao_pdi_id BIGINT,
    componente_id BIGINT,
    submissao_id BIGINT REFERENCES entrega_submissao(id) ON DELETE NO ACTION,
    autor_id UUID NOT NULL REFERENCES usuario(id) ON DELETE NO ACTION,
    tipo VARCHAR(64) NOT NULL,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    justificativa TEXT,
    dados JSONB NOT NULL DEFAULT '{}'::jsonb,
    snapshot JSONB,
    CONSTRAINT fk_evento_versao FOREIGN KEY (pdi_id, pdi_versao_id) REFERENCES pdi_versao(pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT fk_evento_acao FOREIGN KEY (pdi_id, acao_pdi_id) REFERENCES acao_pdi(pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT fk_evento_acao_versao FOREIGN KEY (pdi_versao_id, acao_pdi_id) REFERENCES acao_pdi_versao(pdi_versao_id, acao_pdi_id) ON DELETE NO ACTION,
    CONSTRAINT fk_evento_componente FOREIGN KEY (acao_pdi_id, componente_id) REFERENCES pdi_componente(acao_pdi_id, id) ON DELETE NO ACTION,
    CONSTRAINT ck_evento_componente_acao CHECK (componente_id IS NULL OR acao_pdi_id IS NOT NULL),
    CONSTRAINT ck_evento_submissao_componente CHECK (submissao_id IS NULL OR componente_id IS NOT NULL),
    CONSTRAINT ck_evento_tipo CHECK (NULLIF(BTRIM(tipo), '') IS NOT NULL),
    CONSTRAINT ck_evento_dados CHECK (jsonb_typeof(dados) = 'object'),
    CONSTRAINT ck_evento_snapshot CHECK (snapshot IS NULL OR jsonb_typeof(snapshot) = 'object')
);

